from typing import Protocol
import numpy as np


class CommandSpace(Protocol):
    search_size: int
    native_size: int
    can_spin: bool
    model: object

    def bounds(self) -> tuple[np.ndarray, np.ndarray]: ...
    def to_native_batch(self, search: np.ndarray) -> tuple[np.ndarray, np.ndarray]: ...
    def from_native_batch(self, native: np.ndarray) -> np.ndarray: ...
    def state_coordinates(self, states: np.ndarray) -> np.ndarray: ...
    def desired_coordinates(self, request) -> np.ndarray: ...
    def request_error_batch(self, search, native, request) -> np.ndarray: ...
    def decode_one(self, native, mode='track'): ...
    def yaw_reference(self, search: np.ndarray) -> np.ndarray: ...
    def turn_for_heading(self, error, distance): ...
    def goal_approach_distance(self, lookahead: float) -> float: ...
